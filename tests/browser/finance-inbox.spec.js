test('actual batch upload uses one inbox and saves all receipts before review', async ({page})=>{
 await seed(page)
 await page.addInitScript(()=>{
   localStorage.setItem('lifeos_google_session',JSON.stringify({accessToken:'fake-test-token',user:{id:'test-user'},tokenExpiresAt:Date.now()+3600000}))
   localStorage.setItem('lifeos_drive_folder_id','fake-root')
   localStorage.setItem('lifeos_drive_bills_folder_id','fake-bills')
   localStorage.setItem('lifeos-module-state-v1:finance',JSON.stringify({bills:[],expenses:[]}))
 })
 await page.route('https://www.googleapis.com/**',r=>r.fulfill({status:503,json:{error:{message:'Mock unavailable'}}}))
 let uploads=0
 await page.route('https://www.googleapis.com/upload/drive/v3/files**',r=>{
   if(r.request().postData()?.includes('lifeosfileuploadboundary')) return r.fulfill({json:{id:`uploaded-${++uploads}`}})
   return r.fulfill({json:{id:'state-file',modifiedTime:new Date().toISOString()}})
 })
 await page.goto('/finance')
 await page.getByRole('button',{name:/Bills/}).click()
 await page.locator('input[type=file][multiple]').setInputFiles(Array.from({length:3},(_,i)=>({name:`batch-${i}.pdf`,mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4 synthetic receipt')})))
 const inbox=page.getByRole('region',{name:'Receipt inbox'})
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(3)
 await expect(page.getByRole('button',{name:'Upload bills and receipts'})).toHaveAttribute('aria-disabled','false')
 await inbox.getByRole('button',{name:'Add expense',exact:true}).first().click()
 await page.getByRole('spinbutton',{name:'Amount in INR'}).fill('123')
 await page.getByRole('button',{name:'Save Expense',exact:true}).click()
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(2)
 await expect(page.getByRole('button',{name:'+ Add Entry',exact:true})).toHaveCount(0)
 expect(uploads).toBe(3)
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('lifeos-module-state-v1:finance')))
 expect(saved.bills).toHaveLength(3);expect(saved.expenses).toHaveLength(1)
 await page.screenshot({path:'test-results/finance-inbox-desktop.png',fullPage:true})
})
