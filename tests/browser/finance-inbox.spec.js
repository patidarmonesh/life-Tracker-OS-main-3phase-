import { test, expect } from '@playwright/test'
const date = new Intl.DateTimeFormat('en-CA', { timeZone:'Asia/Kolkata' }).format(new Date())
const bills = Array.from({length:30},(_,i)=>({id:`b${i}`,fileName:`receipt-${i+1}.pdf`,fileType:'application/pdf',suggestedAmount:100+i,suggestedDescription:`Merchant ${i+1}`,suggestedCategory:'Food',uploadedAt:new Date().toISOString(),extractedText:'Receipt'}))
async function seed(page) {
 await page.route('**/api/google-auth?action=config',r=>r.fulfill({json:{configured:false}}))
 await page.route('https://www.googleapis.com/**',r=>r.fulfill({status:401,json:{}}))
 await page.addInitScript(({bills,date})=>{
  if(localStorage.getItem('finance-audit-seeded')) return
  localStorage.clear();localStorage.setItem('finance-audit-seeded','1')
  localStorage.setItem('lifeos_google_session',JSON.stringify({user:{id:'test-user'},tokenExpiresAt:1}))
  localStorage.setItem('lifeos_google_client_id','test-client')
  localStorage.setItem('lifeos-module-state-v1:settings',JSON.stringify({profile:{name:'Test',timezone:'Asia/Kolkata'},preferences:{expenseCategories:['Food'],accounts:['Cash','Bank']}}))
  localStorage.setItem('lifeos-module-state-v1:finance',JSON.stringify({bills,expenses:[{id:'old',date,amount:50,category:'Food',account:'Bank',description:'Lunch'}]}))
 },{bills,date})
}
test('30 receipts: save, next, cancel, reload, search and edit without duplicates', async ({page})=>{
 await seed(page);await page.goto('/finance')
 await page.getByRole('button',{name:/Bills \(30\)/}).click()
 const inbox=page.getByRole('region',{name:'Receipt inbox'})
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(30)
 await inbox.getByRole('button',{name:'Add expense',exact:true}).first().click()
 await page.getByRole('button',{name:'Save Expense',exact:true}).click()
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(29)
 await expect(inbox.getByText('29 remaining · 1 added to expenses')).toBeVisible()
 await inbox.getByRole('button',{name:'Review next receipt'}).click()
 await page.getByRole('button',{name:'Save & next receipt'}).click()
 await expect(page.getByRole('dialog',{name:'Add Expense',exact:true})).toBeVisible()
 await page.getByRole('dialog',{name:'Add Expense',exact:true}).getByRole('button',{name:/Close/}).click()
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(28)
 await page.reload();await page.getByRole('button',{name:/Bills \(28\)/}).click()
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(28)
 await inbox.getByRole('button',{name:'Added (2)',exact:true}).click()
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(2)
 await inbox.getByRole('button',{name:'Edit expense'}).first().click()
 await page.getByRole('button',{name:'Update Expense'}).click()
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('lifeos-module-state-v1:finance')))
 expect(saved.expenses).toHaveLength(3);expect(saved.bills).toHaveLength(30)
 await inbox.getByRole('button',{name:'Needs expense (28)'}).click()
 await inbox.getByRole('textbox',{name:'Search receipts'}).fill('Merchant 30')
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(1)
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:/Bills \(28\)/}).click()
 await expect(inbox.getByTestId('receipt-row')).toHaveCount(28)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'test-results/finance-inbox-mobile.png',fullPage:true})
})
